package com.tokidiscover.app.ui.theme

import androidx.compose.ui.unit.dp

/** Spacing ladder (TokiStudio 0.1.10): one set of numbers for every page. */
object TokiSpacing {
    /** Page side margin. */
    val pageMargin = 24.dp
    /** Padding inside cards and groups. */
    val cardPadding = 24.dp
    /** Gap between cards. */
    val cardSpacing = 16.dp
    /** Settings row height. */
    val settingsRow = 64.dp
    /** Gap between a back chip and a title. */
    val md = 12.dp
    /** Horizontal inset of a title inside its chip. */
    val titleGlyphInset = 16.dp
}
